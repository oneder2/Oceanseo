async page => {
  const assert = (value, message) => { if (!value) throw Error(message); };
  await page.goto("http://127.0.0.1:1421");
  await page.getByRole("heading", { name: "总体待办 0", exact: true }).waitFor();
  const width = () => page.locator(".sidebar").evaluate(el => el.getBoundingClientRect().width);
  const separator = page.getByRole("separator", { name: "调整侧边栏宽度" });
  assert(await width() === 244, "Initial sidebar width");
  const box = await separator.boundingBox();
  await page.mouse.move(box.x + 5, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + 81, box.y + box.height / 2, { steps: 10 });
  await page.mouse.up();
  assert(await width() === 320, "Pointer resize must change actual layout width");
  await page.reload();
  await page.getByRole("heading", { name: "总体待办 0", exact: true }).waitFor();
  assert(await width() === 320, "Width must survive relaunch");
  await separator.focus();
  await page.keyboard.press("ArrowLeft"); assert(await width() === 308, "Keyboard resize");
  await page.keyboard.press("End"); assert(await width() === 360, "Maximum width");
  await page.keyboard.press("Home"); assert(await width() === 200, "Minimum width");
  await separator.dblclick(); assert(await width() === 244, "Double click resets width");
  const firstTop = await page.getByRole("region", { name: "共享任务" }).evaluate(el => el.getBoundingClientRect().top);
  await page.locator(".scene-current").click();
  const menu = page.getByRole("dialog", { name: "切换工作区" });
  assert(await menu.evaluate(el => el.parentElement === document.body && getComputedStyle(el).position === "fixed"), "Picker must be a portal overlay");
  assert(await page.getByRole("region", { name: "共享任务" }).evaluate(el => el.getBoundingClientRect().top) === firstTop, "Opening picker must not shift navigation");
  const glass = await menu.evaluate(el => ({ background: getComputedStyle(el).backgroundColor, blur: getComputedStyle(el).backdropFilter }));
  assert(glass.blur.includes("blur") && (glass.background.includes("0.86") || glass.background.includes("/ 0.86")), "Translucent menu with blur");
  await page.keyboard.press("ArrowDown");
  assert(await page.getByRole("button", { name: "新增工作区", exact: true }).evaluate(el => el === document.activeElement), "Arrow navigation");
  await page.keyboard.press("Escape");
  await menu.waitFor({ state: "hidden" });
  assert(await page.locator(".scene-current").evaluate(el => el === document.activeElement), "Escape restores focus");
  await page.locator(".scene-current").click();
  await page.getByRole("heading", { name: "今日总览", exact: true }).click();
  await menu.waitFor({ state: "hidden" });
  for (const [name, style] of [["项目与决策", "executive"], ["技术实验室", "technical"], ["日常生活", "living"], ["阅读与学习", "study"]]) {
    await page.locator(".scene-current").click();
    await page.getByRole("button", { name: "新增工作区", exact: true }).click();
    await page.getByRole("textbox", { name: "工作区名称", exact: true }).fill(name);
    await page.locator(`.scene-style-options [data-style=${style}]`).click();
    await page.getByRole("button", { name: "创建工作区", exact: true }).click();
    await page.locator(".scene-current").waitFor();
    await page.getByRole("dialog").waitFor({ state: "hidden" });
  }
  await page.locator(".scene-current").click();
  await page.screenshot({ path: "output/playwright/personal-desktop-ui-picker.png" });
  await menu.getByRole("button", { name: "技术实验室", exact: true }).click();
  await page.locator(".scene-current strong").filter({ hasText: "技术实验室" }).waitFor();
  assert(await page.locator("html").getAttribute("data-workspace-style") === "technical", "Custom workspace style");
  assert(await width() === 244, "Width persists between workspaces");
  await page.getByRole("button", { name: "添加工具", exact: true }).click();
  await page.locator(".scene-tool-card").first().hover();
  await page.screenshot({ path: "output/playwright/personal-desktop-ui-library.png" });
  await page.getByRole("button", { name: "关闭工作区面板", exact: true }).click();
  await page.locator(".scene-current").click();
  await menu.getByRole("button", { name: "主工作区 · 主工作区", exact: true }).click();
  await page.getByRole("heading", { name: "总体待办 0", exact: true }).waitFor();
  const sizes = [];
  for (const [w, h] of [[1400, 950], [780, 820], [620, 560]]) {
    await page.setViewportSize({ width: w, height: h });
    const dimensions = await page.locator("main.workspace").evaluate(el => ({ scroll: el.scrollWidth, client: el.clientWidth, document: document.documentElement.scrollWidth, viewport: innerWidth }));
    assert(dimensions.scroll <= dimensions.client + 1 && dimensions.document <= dimensions.viewport, `No horizontal overflow at ${w}x${h}: ${JSON.stringify(dimensions)}`);
    await page.locator(".scene-current").click();
    const bounds = await menu.boundingBox();
    assert(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= w + 1 && bounds.y + bounds.height <= h + 1, "Menu stays inside viewport");
    await page.keyboard.press("Escape");
    await page.screenshot({ path: `output/playwright/personal-desktop-ui-${w}.png` });
    sizes.push({ width: w, height: h, ...dimensions });
  }
  await page.setViewportSize({ width: 1400, height: 950 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.getByRole("button", { name: "今天", exact: true }).click();
  assert(await page.locator("main.workspace").evaluate(el => el.getAnimations().length) === 0, "Reduced motion suppresses page animation");
  await page.locator(".scene-current").click();
  assert(await menu.evaluate(el => getComputedStyle(el).animationName) === "none", "Reduced motion suppresses menu animation");
  await page.keyboard.press("Escape");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.getByRole("button", { name: "主页", exact: true }).click();
  return { pointerResize: true, keyboardResize: true, persistedWidth: true, reset: true, floatingPicker: true, stableNavigation: true, glass, keyboardPicker: true, outsideDismiss: true, workspaceStyles: true, reducedMotion: true, sizes };
}
