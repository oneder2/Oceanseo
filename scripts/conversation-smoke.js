// Run with playwright-cli against an isolated Vite dev preview. Local fixture, no paid AI.
async (page) => {
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const check=(v,m)=>{if(!v)throw Error(m);};
  const reply=await (await page.request.get(new URL('/tests/fixtures/dialogue-reply.json', page.url()).href)).json();
  await page.setViewportSize({width:1440,height:960});
  await page.getByRole('navigation',{name:'工作区导航'}).getByRole('button',{name:'想法与目标',exact:true}).click();
  await page.getByRole('textbox',{name:'给小汐的消息'}).waitFor();
  await page.screenshot({path:'output/playwright/conversation-empty.png',animations:'disabled'});
  await page.evaluate(reply=>{
    const now=new Date().toISOString();
    const s=JSON.parse(localStorage.getItem('tideplan.goals.v1'));
    s.preferences.checkins=false;
    const p={id:'qa-proposal',createdAt:now,sourceIds:[],goalSnapshot:JSON.stringify({goals:s.goals,actions:s.actions}),taskVersions:{},status:'pending',plan:reply.plan,waiting:reply.waiting};
    s.proposals=[p];s.conversation={messages:[{id:'qa-user',role:'user',text:'发布和旅行挤在一起。先做完验证再发布；旅行想去杭州，但没想好玩什么。',createdAt:now},{id:'qa-reply',role:'assistant',text:reply.reply,createdAt:now}],understanding:reply.understanding,proposalId:p.id,receipts:[],needsReply:false};
    localStorage.setItem('tideplan.goals.v1',JSON.stringify(s));
  },reply);
  await page.reload();
  await page.getByRole('navigation',{name:'工作区导航'}).getByRole('button',{name:'想法与目标',exact:true}).click();
  await page.getByText(reply.reply,{exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/conversation-chat.png',animations:'disabled'});
  await page.getByRole('button',{name:'查看理解图',exact:true}).click();
  const map=page.getByRole('dialog',{name:'理解图',exact:true});
  check(await map.locator('input,textarea,select,[contenteditable=true]').count()===0,'Understanding must be read-only');
  await map.getByText('尚缺信息',{exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/conversation-map.png',animations:'disabled'});
  await map.getByRole('button',{name:'讨论周末旅行的目的',exact:true}).click();
  check((await page.getByRole('textbox',{name:'给小汐的消息'}).inputValue()).includes('旅行的目的'),'Discussion reference missing');
  await page.getByRole('textbox',{name:'给小汐的消息'}).fill('');
  await page.getByRole('button',{name:'打开交付清单',exact:true}).click();
  const panel=page.getByRole('dialog',{name:'最终交付清单',exact:true});
  const action=panel.getByRole('article',{name:'验证升级与恢复',exact:true});
  check(await action.getByRole('button',{name:'执行本条',exact:true}).isDisabled(),'Action should wait for goal creation');
  await action.getByRole('button',{name:'微调参数',exact:true}).click();
  await action.getByRole('spinbutton',{name:'预计分钟',exact:true}).fill('40');
  await action.getByRole('button',{name:'保存微调',exact:true}).click();
  await action.getByText('40 分钟',{exact:false}).first().waitFor();
  await panel.getByRole('article',{name:'稳妥发布应用',exact:true}).getByRole('button',{name:'执行本条',exact:true}).click();
  await action.getByRole('button',{name:'执行本条',exact:true}).click();
  check(await panel.getByRole('article',{name:'拟定旅行路线',exact:true}).getByRole('button',{name:'执行本条',exact:true}).isDisabled(),'Unclear branch executed');
  await panel.getByRole('button',{name:'撤销最近一次执行',exact:true}).click();
  await panel.getByRole('button',{name:'确认撤销',exact:true}).click();
  await action.waitFor();
  check(await page.evaluate(()=>JSON.parse(localStorage.getItem('tideplan.tasks.v1')).length)===0,'Undo left task');
  await panel.getByRole('button',{name:'执行全部可执行项（1）',exact:true}).click();
  check(await page.evaluate(()=>JSON.parse(localStorage.getItem('tideplan.tasks.v1')).length)===1,'Batch created duplicate tasks');
  await page.screenshot({path:'output/playwright/conversation-delivery.png',animations:'disabled'});
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'查看理解图',exact:true}).click();
  await page.getByText('最新微调 · 验证升级与恢复',{exact:true}).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('textbox',{name:'给小汐的消息'}).fill('旅行先放下，这周只做发布。');
  await page.getByRole('button',{name:'发送消息',exact:true}).click();
  await page.getByText('消息已保存在本机。浏览器预览不连接 AI，请在桌面应用中继续对话。',{exact:true}).waitFor();
  await page.reload();
  await page.getByRole('navigation',{name:'工作区导航'}).getByRole('button',{name:'想法与目标',exact:true}).click();
  await page.getByText('旅行先放下，这周只做发布。',{exact:true}).waitFor();
  await page.setViewportSize({width:620,height:560});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Narrow page overflow');
  await page.getByRole('textbox',{name:'给小汐的消息'}).fill('待续草稿');
  await page.screenshot({path:'output/playwright/conversation-narrow.png',animations:'disabled'});
  await page.getByRole('button',{name:'打开交付清单',exact:true}).click();
  check(await panel.getByRole('button',{name:'执行全部可执行项',exact:true}).isDisabled(),'Stale list executable after new message');
  await page.keyboard.press('Tab');
  check(await page.evaluate(()=>!!document.activeElement.closest('[role=dialog]')),'Focus escaped drawer');
  await page.screenshot({path:'output/playwright/conversation-narrow-drawer.png',animations:'disabled'});
  await page.keyboard.press('Escape');
  check(errors.length===0,errors.join('\n'));
}
